export function summaryKo(version) {
  const note = version === SUMMARY_VERSION ? [] : ['', `> 이 요약은 확장 프로그램 ${SUMMARY_VERSION} 기준입니다. 지금 원문(${version})과 다를 수 있으니 차이가 궁금하면 Claude에게 물어보세요.`]
  return [...LINES, ...note].join('\n')
}
